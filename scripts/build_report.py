def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def fmt(value: float) -> str:
    return f"{value:.4f}".replace(".", ",")


class Report:
    def __init__(self) -> None:
        self.doc = docx.Document()
        self._setup_styles()
        self._setup_page()
        self.figure_number = 0
        self.table_number = 0

    # ------------------------------------------------------------------
    # Оформление
    # ------------------------------------------------------------------
    def _setup_page(self) -> None:
        for section in self.doc.sections:
            section.top_margin = Cm(2.0)
            section.bottom_margin = Cm(2.0)
            section.left_margin = Cm(3.0)
            section.right_margin = Cm(1.5)

    def _setup_styles(self) -> None:
        styles = self.doc.styles
        normal = styles["Normal"]
        normal.font.name = "Times New Roman"
        normal.font.size = Pt(12)
        normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        normal.paragraph_format.line_spacing = 1.15
        normal.paragraph_format.space_after = Pt(0)

    def _run(self, paragraph, text, *, bold=False, italic=False, size=12):
        run = paragraph.add_run(text)
        run.font.name = "Times New Roman"
        run.font.size = Pt(size)
        run.bold = bold
        run.italic = italic
        return run

    def title_page(self) -> None:
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(12)
        self._run(
            p,
            "Федеральное государственное бюджетное образовательное учреждение\n"
            "высшего образования\n"
            "«Национальный исследовательский университет „МЭИ“»\n"
            "Институт информатики и вычислительной техники\n"
            "Кафедра вычислительных машин, систем и сетей",
            size=12,
        )

        for _ in range(5):
            self.doc.add_paragraph()

        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(24)
        self._run(
            p,
            "ОТЧЁТ ПО КУРСОВОЙ РАБОТЕ\n"
            "по дисциплине\n"
            "«Цифровые технологии защиты информации»\n\n"
            "Распознавание и синонимическое обезличивание\n"
            "персональных данных\n\n"
            f"Вариант {VARIANT}",
            bold=True,
            size=15,
        )

        for _ in range(5):
            self.doc.add_paragraph()

        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        self._run(
            p,
            "Выполнил:\n"
            f"студент группы {GROUP}\n"
            f"{AUTHOR}\n\n"
            f"Москва {YEAR}",
            size=12,
        )
        self.doc.add_page_break()

    def h1(self, text: str, *, page_break: bool = True) -> None:
        if page_break:
            self.doc.add_page_break()
        p = self.doc.add_paragraph()
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(10)
        p.paragraph_format.keep_with_next = True
        self._run(p, text, bold=True, size=15)

    def h2(self, text: str) -> None:
        p = self.doc.add_paragraph()
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.keep_with_next = True
        self._run(p, text, bold=True, size=13)

    def h3(self, text: str) -> None:
        p = self.doc.add_paragraph()
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.keep_with_next = True
        self._run(p, text, bold=True, size=12)

    def p(self, text: str, *, first_line: bool = True, align=None) -> None:
        paragraph = self.doc.add_paragraph()
        paragraph.paragraph_format.line_spacing = 1.15
        paragraph.paragraph_format.space_after = Pt(6)
        paragraph.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
        if first_line:
            paragraph.paragraph_format.first_line_indent = Cm(1.25)
        self._run(paragraph, text)

    def bullet(self, text: str) -> None:
        paragraph = self.doc.add_paragraph(style="List Bullet")
        paragraph.paragraph_format.line_spacing = 1.15
        paragraph.paragraph_format.space_after = Pt(2)
        paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        self._run(paragraph, text)

    def formula(self, text: str) -> None:
        paragraph = self.doc.add_paragraph()
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
        paragraph.paragraph_format.space_before = Pt(4)
        paragraph.paragraph_format.space_after = Pt(6)
        self._run(paragraph, text, italic=True, size=12)

    def caption(self, text: str) -> None:
        self.table_number += 1
        paragraph = self.doc.add_paragraph()
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
        paragraph.paragraph_format.space_before = Pt(8)
        paragraph.paragraph_format.space_after = Pt(3)
        paragraph.paragraph_format.keep_with_next = True
        self._run(paragraph, f"Таблица {self.table_number} — {text}", size=11)

    def note(self, text: str) -> None:
        paragraph = self.doc.add_paragraph()
        paragraph.paragraph_format.space_after = Pt(8)
        self._run(paragraph, text, italic=True, size=10)

    def table(self, headers: list[str], rows: list[list[str]], widths=None) -> None:
        table = self.doc.add_table(rows=1, cols=len(headers))
        table.style = "Table Grid"
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        header = table.rows[0].cells
        for index, text in enumerate(headers):
            header[index].text = ""
            paragraph = header[index].paragraphs[0]
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            self._run(paragraph, text, bold=True, size=10)
            self._shade(header[index], "D9E2F3")
        for row in rows:
            cells = table.add_row().cells
            for index, text in enumerate(row):
                cells[index].text = ""
                paragraph = cells[index].paragraphs[0]
                paragraph.alignment = (
                    WD_ALIGN_PARAGRAPH.LEFT if index == 0 else WD_ALIGN_PARAGRAPH.CENTER
                )
                self._run(paragraph, str(text), size=10)
        if widths:
            for row in table.rows:
                for index, width in enumerate(widths):
                    row.cells[index].width = Cm(width)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(2)

    @staticmethod
    def _shade(cell, color: str) -> None:
        tc_pr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), color)
        tc_pr.append(shd)

    def save(self) -> None:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        self.doc.save(OUT)


